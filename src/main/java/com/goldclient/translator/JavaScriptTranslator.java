package com.goldclient.translator;

import com.goldclient.model.IrMethodModel;
import java.util.ArrayList;
import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Produces JavaScript modules from the current semantic-IR reconstruction.
 *
 * <p>This first executable-JS backend intentionally reuses the structured
 * control-flow reconstruction, then lowers Java-only declarations and common
 * library calls into JavaScript syntax. It reports incomplete methods whenever
 * the source translator left unsupported IR or the lowering encountered syntax
 * it cannot safely convert. It does not imply Minecraft/Forge APIs exist in JS.</p>
 */
public final class JavaScriptTranslator {
  private static final Pattern SIGNATURE = Pattern.compile(
      "(?m)^\\s*[\\w.$<>\\[\\]]+\\s+([\\w$]+)\\(([^)]*)\\) \\{");
  private static final Pattern CATCH = Pattern.compile(
      "catch\\s*\\(\\s*[\\w.$]+\\s+([\\w$]+)\\s*\\)");
  private static final Pattern LOCAL_TYPE = Pattern.compile(
      "\\b(?:Object|String|Boolean|Byte|Character|Short|Integer|Long|Float|Double|"
          + "boolean|byte|char|short|int|long|float|double)\\s+(local\\d+)\\s*=");
  private final JavaTranslator structuredTranslator;

  public JavaScriptTranslator() {
    this(new JavaTranslator());
  }

  JavaScriptTranslator(JavaTranslator structuredTranslator) {
    this.structuredTranslator = structuredTranslator;
  }

  public TranslationResult translate(IrMethodModel method) {
    TranslationResult structured = structuredTranslator.translate(method);
    String javaSource = structured.source();
    Matcher signature = SIGNATURE.matcher(javaSource);
    if (!signature.find()) {
      return new TranslationResult(
          "export function " + safeIdentifier(method.name()) + "() {\n"
              + "  throw new Error(" + quote("Unable to lower method signature") + ");\n"
              + "}\n",
          false);
    }

    String originalName = signature.group(1);
    String parameters = lowerParameters(signature.group(2));
    String exportName = exportedName(originalName, method.descriptor());
    int bodyStart = javaSource.indexOf('{', signature.start());
    int bodyEnd = javaSource.lastIndexOf('}');
    if (bodyStart < 0 || bodyEnd <= bodyStart) {
      return new TranslationResult(
          "export function " + exportName + "(" + parameters + ") {\n"
              + "  throw new Error(" + quote("Malformed intermediate method body") + ");\n"
              + "}\n",
          false);
    }

    String body = javaSource.substring(bodyStart + 1, bodyEnd);
    body = lowerJavaSyntax(body);
    boolean complete = structured.complete()
        && !body.contains("TODO:")
        && !body.contains("CONTROL-FLOW ERROR")
        && !body.contains("<exception>")
        && !body.contains("Unsupported JVM IR");

    StringBuilder output = new StringBuilder();
    output.append("// Generated by Gold Client JavaScriptTranslator.\n")
        .append("// Status: ").append(complete ? "complete for represented IR" : "incomplete")
        .append("\n")
        .append("// Host APIs such as Minecraft/Forge must be supplied by an adapter.\n")
        .append("export function ").append(exportName).append("(")
        .append(parameters).append(") {\n")
        .append(body.stripTrailing()).append("\n")
        .append("}\n");
    return new TranslationResult(output.toString(), complete);
  }

  /** Lowers the source-like output while preserving quoted strings and comments. */
  String lowerJavaSyntax(String source) {
    StringBuilder tokens = new StringBuilder(source.length() + 32);
    LexicalState state = LexicalState.CODE;
    for (int i = 0; i < source.length(); i++) {
      char current = source.charAt(i);
      char next = i + 1 < source.length() ? source.charAt(i + 1) : '\0';
      if (state == LexicalState.CODE) {
        if (current == '"' ) {
          state = LexicalState.STRING;
          tokens.append(current);
        } else if (current == '\'') {
          state = LexicalState.CHARACTER;
          tokens.append('"');
        } else if (current == '/' && next == '/') {
          state = LexicalState.LINE_COMMENT;
          tokens.append("//");
          i++;
        } else if (current == '/' && next == '*') {
          state = LexicalState.BLOCK_COMMENT;
          tokens.append("/*");
          i++;
        } else {
          tokens.append(current);
        }
      } else if (state == LexicalState.STRING) {
        tokens.append(current);
        if (current == '\\' && i + 1 < source.length()) tokens.append(source.charAt(++i));
        else if (current == '"') state = LexicalState.CODE;
      } else if (state == LexicalState.CHARACTER) {
        if (current == '\\' && i + 1 < source.length()) {
          tokens.append(escapeChar(source.charAt(++i)));
        } else if (current == '\'') {
          tokens.append('"');
          state = LexicalState.CODE;
        } else {
          tokens.append(escapeChar(current));
        }
      } else if (state == LexicalState.LINE_COMMENT) {
        tokens.append(current);
        if (current == '\n') state = LexicalState.CODE;
      } else {
        tokens.append(current);
        if (current == '*' && next == '/') {
          tokens.append('/');
          i++;
          state = LexicalState.CODE;
        }
      }
    }

    String result = tokens.toString();
    Matcher catchMatcher = CATCH.matcher(result);
    StringBuffer catchBuffer = new StringBuffer();
    while (catchMatcher.find()) {
      catchMatcher.appendReplacement(catchBuffer,
          Matcher.quoteReplacement("catch (" + catchMatcher.group(1) + ")"));
    }
    catchMatcher.appendTail(catchBuffer);
    result = catchBuffer.toString();

    Matcher typedLocal = LOCAL_TYPE.matcher(result);
    StringBuffer localBuffer = new StringBuffer();
    while (typedLocal.find()) {
      typedLocal.appendReplacement(localBuffer,
          Matcher.quoteReplacement("let " + typedLocal.group(1) + " ="));
    }
    typedLocal.appendTail(localBuffer);
    result = localBuffer.toString();

    result = result.replace("System.out.println(", "console.log(")
        .replace("System.err.println(", "console.error(")
        .replace("java.lang.IllegalStateException", "Error")
        .replace("java.lang.IllegalArgumentException", "Error")
        .replace("java.lang.NullPointerException", "TypeError")
        .replace("java.lang.UnsupportedOperationException", "Error")
        .replace("java.lang.RuntimeException", "Error")
        .replace("java.lang.Exception", "Error")
        .replace("java.lang.String.valueOf(", "String(")
        .replace("Integer.toString(", "String(")
        .replace("Boolean.toString(", "String(")
        .replace("Math.floorDiv(", "GoldClientRuntime.intDiv(")
        .replace("Math.floorMod(", "GoldClientRuntime.intMod(");
    return result;
  }

  private static String lowerParameters(String parameters) {
    if (parameters == null || parameters.isBlank()) return "";
    List<String> lowered = new ArrayList<>();
    for (String parameter : parameters.split(",")) {
      String trimmed = parameter.trim();
      int lastSpace = trimmed.lastIndexOf(' ');
      String name = lastSpace >= 0 ? trimmed.substring(lastSpace + 1) : trimmed;
      lowered.add(safeIdentifier(name));
    }
    return String.join(", ", lowered);
  }

  private static String exportedName(String name, String descriptor) {
    String suffix = Integer.toUnsignedString(
        (descriptor == null ? "" : descriptor).hashCode(), 36);
    return safeIdentifier(name) + "__" + suffix;
  }

  private static String safeIdentifier(String value) {
    String safe = value == null ? "translatedMethod" : value.replaceAll("[^A-Za-z0-9_$]", "_");
    if (safe.isBlank()) safe = "translatedMethod";
    if (!Character.isJavaIdentifierStart(safe.charAt(0))) safe = "_" + safe;
    return safe;
  }

  private static String quote(String value) {
    return "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"")
        .replace("\n", "\\n").replace("\r", "\\r") + "\"";
  }

  private static String escapeChar(char value) {
    return switch (value) {
      case '\n' -> "\\n";
      case '\r' -> "\\r";
      case '\t' -> "\\t";
      case '"' -> "\\\"";
      default -> String.valueOf(value);
    };
  }

  private enum LexicalState { CODE, STRING, CHARACTER, LINE_COMMENT, BLOCK_COMMENT }
}