package com.goldclient.translator;

import com.goldclient.model.IrMethodModel;
import java.util.ArrayList;
import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Produces JavaScript modules from the current semantic-IR reconstruction.
 *
 * <p>This first executable-JS backend intentionally reuses the structured
 * control-flow reconstruction, then lowers Java-only declarations and common
 * library calls into JavaScript syntax. It reports incomplete methods whenever
 * the source translator left unsupported IR or the lowering encountered syntax
 * it cannot safely convert. It does not imply Minecraft/Forge APIs exist in JS.</p>
 */
public final class JavaScriptTranslator {
  private static final Pattern SIGNATURE = Pattern.compile(
      "(?m)^\\s*[\\w.$<>\\[\\]]+\\s+([\\w$<>]+)\\(([^)]*)\\) \\{");
  private static final Pattern CATCH = Pattern.compile(
      "catch\\s*\\(\\s*[\\w.$]+\\s+([\\w$]+)\\s*\\)");
  private static final Pattern LOCAL_TYPE = Pattern.compile(
      "\\b(?:Object|String|Boolean|Byte|Character|Short|Integer|Long|Float|Double|"
          + "boolean|byte|char|short|int|long|float|double)\\s+(local\\d+)\\s*=");
  private final JavaTranslator structuredTranslator;

  public JavaScriptTranslator() {
    this(new JavaTranslator());
  }

  JavaScriptTranslator(JavaTranslator structuredTranslator) {
    this.structuredTranslator = structuredTranslator;
  }

  public TranslationResult translate(IrMethodModel method) {
    return translate(method, true);
  }

  public TranslationResult translate(IrMethodModel method, boolean isStatic) {
    TranslationResult structured = structuredTranslator.translate(method);
    String javaSource = structured.source();
    Matcher signature = SIGNATURE.matcher(javaSource);
    if (!signature.find()) {
      return new TranslationResult(
          "export function " + safeIdentifier(method.name()) + "() {\n"
              + "  throw new Error(" + quote("Unable to lower method signature") + ");\n"
              + "}\n",
          false);
    }

    String originalName = signature.group(1);
    String parameters = lowerParameters(signature.group(2), isStatic);
    String exportName = exportedName(originalName, method.descriptor());
    int bodyStart = javaSource.indexOf('{', signature.start());
    int bodyEnd = javaSource.lastIndexOf('}');
    if (bodyStart < 0 || bodyEnd <= bodyStart) {
      return new TranslationResult(
          "export function " + exportName + "(" + parameters + ") {\n"
              + "  throw new Error(" + quote("Malformed intermediate method body") + ");\n"
              + "}\n",
          false);
    }

    String body = javaSource.substring(bodyStart + 1, bodyEnd);
    if (!isStatic) body = body.replaceAll("\\blocal0\\b", "this");
    boolean hasUnsupportedMarkers = body.contains("TODO:")
        || body.contains("CONTROL-FLOW ERROR")
        || body.contains("<exception>")
        || body.contains("Unsupported JVM IR");
    body = lowerJavaSyntax(body);
    body = makeUnsupportedOperationsExplicit(body);
    boolean complete = structured.complete() && !hasUnsupportedMarkers;

    StringBuilder output = new StringBuilder();
    output.append("// Generated by Gold Client JavaScriptTranslator.\n")
        .append("// Status: ").append(complete ? "complete for represented IR" : "incomplete")
        .append("\n")
        .append("// Host APIs such as Minecraft/Forge must be supplied by an adapter.\n")
        .append("export function ").append(exportName).append("(")
        .append(parameters).append(") {\n")
        .append(body.stripTrailing()).append("\n")
        .append("}\n");
    return new TranslationResult(output.toString(), complete);
  }

  /**
   * Emits an explicit executable stub when bytecode is unavailable. Keeping
   * the symbol present makes the module graph complete without pretending
   * that native/abstract behavior was reconstructed.
   */
  public TranslationResult translateStub(String methodName, String descriptor, String reason) {
    return translateStub(methodName, descriptor, reason, true);
  }

  public TranslationResult translateStub(String methodName, String descriptor, String reason, boolean isStatic) {
    String signatureSource = structuredTranslator.translate(
        new IrMethodModel(methodName, descriptor, List.of())).source();
    Matcher signature = SIGNATURE.matcher(signatureSource);
    String parameters = "";
    String exportName = exportedName(methodName, descriptor);
    if (signature.find()) parameters = lowerParameters(signature.group(2), isStatic);
    String detail = methodName + (descriptor == null ? "" : descriptor) + ": "
        + (reason == null ? "bytecode unavailable" : reason);
    String source = "// Status: stubbed; original implementation was unavailable.\n"
        + "export function " + exportName + "(" + parameters + ") {\n"
        + "  return GoldClientRuntime.unsupported(\"untranslated-method\", " + quote(detail) + ");\n"
        + "}\n";
    return new TranslationResult(source, false);
  }

  private static String makeUnsupportedOperationsExplicit(String source) {
    Pattern todoPattern = Pattern.compile("(?m)^(\\s*)// TODO: ([A-Z_]+)(?: (.*))?$");
    Matcher todo = todoPattern.matcher(source);
    StringBuffer lowered = new StringBuffer();
    while (todo.find()) {
      String kind = todo.group(2);
      String detail = todo.group(3) == null ? "" : todo.group(3).trim();
      String replacement = todo.group(1) + "GoldClientRuntime.unsupported("
          + quote(kind) + ", " + quote(detail) + ");";
      todo.appendReplacement(lowered, Matcher.quoteReplacement(replacement));
    }
    todo.appendTail(lowered);

    Pattern auditPattern = Pattern.compile("(?m)^(\\s*)// CONTROL-FLOW ERROR at operation (.*)$");
    Matcher audit = auditPattern.matcher(lowered.toString());
    StringBuffer audited = new StringBuffer();
    while (audit.find()) {
      String replacement = audit.group(1) + "GoldClientRuntime.unsupported("
          + quote("control-flow-audit") + ", " + quote(audit.group(2).trim()) + ");";
      audit.appendReplacement(audited, Matcher.quoteReplacement(replacement));
    }
    audit.appendTail(audited);
    return audited.toString();
  }

  /** Lowers the source-like output while preserving quoted strings and comments. */
  String lowerJavaSyntax(String source) {
    StringBuilder tokens = new StringBuilder(source.length() + 32);
    LexicalState state = LexicalState.CODE;
    for (int i = 0; i < source.length(); i++) {
      char current = source.charAt(i);
      char next = i + 1 < source.length() ? source.charAt(i + 1) : '\0';
      if (state == LexicalState.CODE) {
        if (current == '"' ) {
          state = LexicalState.STRING;
          tokens.append(current);
        } else if (current == '\'') {
          state = LexicalState.CHARACTER;
          tokens.append('"');
        } else if (current == '/' && next == '/') {
          state = LexicalState.LINE_COMMENT;
          tokens.append("//");
          i++;
        } else if (current == '/' && next == '*') {
          state = LexicalState.BLOCK_COMMENT;
          tokens.append("/*");
          i++;
        } else {
          tokens.append(current);
        }
      } else if (state == LexicalState.STRING) {
        tokens.append(current);
        if (current == '\\' && i + 1 < source.length()) tokens.append(source.charAt(++i));
        else if (current == '"') state = LexicalState.CODE;
      } else if (state == LexicalState.CHARACTER) {
        if (current == '\\' && i + 1 < source.length()) {
          tokens.append(escapeChar(source.charAt(++i)));
        } else if (current == '\'') {
          tokens.append('"');
          state = LexicalState.CODE;
        } else {
          tokens.append(escapeChar(current));
        }
      } else if (state == LexicalState.LINE_COMMENT) {
        tokens.append(current);
        if (current == '\n') state = LexicalState.CODE;
      } else {
        tokens.append(current);
        if (current == '*' && next == '/') {
          tokens.append('/');
          i++;
          state = LexicalState.CODE;
        }
      }
    }

    String result = tokens.toString();
    Matcher catchMatcher = CATCH.matcher(result);
    StringBuffer catchBuffer = new StringBuffer();
    while (catchMatcher.find()) {
      catchMatcher.appendReplacement(catchBuffer,
          Matcher.quoteReplacement("catch (" + catchMatcher.group(1) + ")"));
    }
    catchMatcher.appendTail(catchBuffer);
    result = catchBuffer.toString();

    Matcher typedLocal = LOCAL_TYPE.matcher(result);
    StringBuffer localBuffer = new StringBuffer();
    while (typedLocal.find()) {
      typedLocal.appendReplacement(localBuffer,
          Matcher.quoteReplacement("let " + typedLocal.group(1) + " ="));
    }
    typedLocal.appendTail(localBuffer);
    result = localBuffer.toString();

    return replaceCodeTokens(result);
  }

  /**
   * Rewrites Java API spellings only in executable code, never inside string
   * literals or comments. This matters for mods that log class names or source
   * snippets containing Java syntax as ordinary text.
   */
  private static String replaceCodeTokens(String source) {
    StringBuilder output = new StringBuilder(source.length() + 32);
    StringBuilder code = new StringBuilder();
    LexicalState state = LexicalState.CODE;
    for (int i = 0; i < source.length(); i++) {
      char current = source.charAt(i);
      char next = i + 1 < source.length() ? source.charAt(i + 1) : '\0';
      if (state == LexicalState.CODE) {
        if (current == '"') {
          output.append(rewriteCode(code));
          code.setLength(0);
          state = LexicalState.STRING;
          output.append(current);
        } else if (current == '/' && next == '/') {
          output.append(rewriteCode(code));
          code.setLength(0);
          state = LexicalState.LINE_COMMENT;
          output.append("//");
          i++;
        } else if (current == '/' && next == '*') {
          output.append(rewriteCode(code));
          code.setLength(0);
          state = LexicalState.BLOCK_COMMENT;
          output.append("/*");
          i++;
        } else {
          code.append(current);
        }
      } else if (state == LexicalState.STRING) {
        output.append(current);
        if (current == '\\' && i + 1 < source.length()) output.append(source.charAt(++i));
        else if (current == '"') state = LexicalState.CODE;
      } else if (state == LexicalState.LINE_COMMENT) {
        output.append(current);
        if (current == '\n') state = LexicalState.CODE;
      } else {
        output.append(current);
        if (current == '*' && next == '/') {
          output.append('/');
          i++;
          state = LexicalState.CODE;
        }
      }
    }
    output.append(rewriteCode(code));
    return output.toString();
  }

  private static String rewriteCode(StringBuilder input) {
    String result = input.toString()
        .replace("System.out.println(", "console.log(")
        .replace("System.err.println(", "console.error(")
        .replace("new java.lang.IllegalStateException", "new Error")
        .replace("new java.lang.IllegalArgumentException", "new Error")
        .replace("new java.lang.NullPointerException", "new TypeError")
        .replace("new java.lang.UnsupportedOperationException", "new Error")
        .replace("new java.lang.RuntimeException", "new Error")
        .replace("new java.lang.Exception", "new Error")
        .replace("java.lang.String.valueOf(", "String(")
        .replace("Integer.toString(", "String(")
        .replace("Boolean.toString(", "String(")
        .replace("Math.floorDiv(", "GoldClientRuntime.intDiv(")
        .replace("Math.floorMod(", "GoldClientRuntime.intMod(")
        .replace("java.util.Objects.requireNonNull(", "GoldClientRuntime.requireNonNull(")
        .replace("Objects.requireNonNull(", "GoldClientRuntime.requireNonNull(")
        .replace("java.lang.System.arraycopy(", "GoldClientRuntime.arraycopy(")
        .replace("System.arraycopy(", "GoldClientRuntime.arraycopy(");

    // Route fully-qualified calls on translated classes through the class registry.
    // Java standard-library calls are handled by dedicated compatibility helpers.
    java.util.regex.Matcher staticCall = java.util.regex.Pattern.compile(
        "(?<![A-Za-z0-9_$])((?:[a-z_$][\\\\w$]*\\\\.)*[A-Z][A-Za-z0-9_$]*)\\\\.([A-Za-z_$][A-Za-z0-9_$]*)\\\\(")
        .matcher(result);
    StringBuffer staticCalls = new StringBuffer();
    while (staticCall.find()) {
      String owner = staticCall.group(1);
      if (owner.startsWith("java.") || owner.startsWith("javax.")
          || owner.startsWith("org.") || owner.startsWith("com.google.")) {
        staticCall.appendReplacement(staticCalls, java.util.regex.Matcher.quoteReplacement(staticCall.group()));
      } else {
        String replacement = "GoldClientRuntime.invokeStaticClass(" + quote(owner.replace('/', '.'))
            + ", " + quote(staticCall.group(2)) + ", ";
        staticCall.appendReplacement(staticCalls, java.util.regex.Matcher.quoteReplacement(replacement));
      }
    }
    staticCall.appendTail(staticCalls);
    result = staticCalls.toString();

    // Constructor expressions for mod classes resolve through the generated registry.
    java.util.regex.Matcher allocation = java.util.regex.Pattern.compile(
        "\\\\bnew\\\\s+((?:[a-z_$][\\\\w$]*\\\\.)+[A-Z][A-Za-z0-9_$]*)\\\\s*\\\\(")
        .matcher(result);
    StringBuffer allocations = new StringBuffer();
    while (allocation.find()) {
      String replacement = "GoldClientRuntime.create(" + quote(allocation.group(1).replace('/', '.')) + ", ";
      allocation.appendReplacement(allocations, java.util.regex.Matcher.quoteReplacement(replacement));
    }
    allocation.appendTail(allocations);
    result = allocations.toString();

    // JVM numeric literals carry suffixes which are not valid JavaScript.
    result = result.replaceAll(
        "\\b(-?(?:0[xX][0-9a-fA-F]+|(?:[0-9]+(?:\\.[0-9]*)?|\\.[0-9]+)(?:[eE][+-]?[0-9]+)?))[lLfFdD]\\b",
        "$1");

    // Primitive casts are compile-time hints on the JS target; int conversion
    // is explicit where Java's 32-bit semantics matter.
    result = result.replaceAll("\\((?:byte|short|float|double|char)\\)\\s*(?=[A-Za-z_$0-9(])", "");
    result = result.replaceAll("\\(long\\)\\s*(?=[A-Za-z_$0-9(])", "");
    result = result.replaceAll(
        "\\(int\\)\\s*([A-Za-z_$][\\w$]*|[-+]?[0-9]+|\\([^()]*\\))",
        "GoldClientRuntime.toInt32($1)");

    // Primitive JVM arrays must be allocated with JavaScript-compatible syntax.
    java.util.regex.Matcher array = java.util.regex.Pattern.compile(
        "\\bnew\\s+(boolean|byte|char|short|int|long|float|double|Object)\\s*\\[([^\\[\\]]*)\\]")
        .matcher(result);
    StringBuffer arrays = new StringBuffer();
    while (array.find()) {
      array.appendReplacement(arrays, java.util.regex.Matcher.quoteReplacement(
          "GoldClientRuntime.newArray(" + quote(array.group(1)) + ", " + array.group(2) + ")"));
    }
    array.appendTail(arrays);
    result = arrays.toString();

    // Common Java value APIs with direct equivalents in the compatibility layer.
    java.util.regex.Matcher equals = java.util.regex.Pattern.compile(
        "([A-Za-z_$][\\w$]*(?:\\.[A-Za-z_$][\\w$]*)*)\\.equals\\(([^()]*?)\\)")
        .matcher(result);
    StringBuffer equalCalls = new StringBuffer();
    while (equals.find()) {
      equals.appendReplacement(equalCalls, java.util.regex.Matcher.quoteReplacement(
          "GoldClientRuntime.javaEquals(" + equals.group(1) + ", " + equals.group(2) + ")"));
    }
    equals.appendTail(equalCalls);
    return equalCalls.toString();
  }

  private static String lowerParameters(String parameters, boolean isStatic) {
    if (parameters == null || parameters.isBlank()) return "";
    List<String> lowered = new ArrayList<>();
    int localSlot = isStatic ? 0 : 1;
    for (String parameter : parameters.split(",")) {
      String trimmed = parameter.trim();
      int lastSpace = trimmed.lastIndexOf(' ');
      if (lastSpace < 0) {
        lowered.add(safeIdentifier(trimmed));
        continue;
      }
      String type = trimmed.substring(0, lastSpace).trim();
      if (isStatic) {
        lowered.add(safeIdentifier(trimmed.substring(lastSpace + 1)));
      } else {
        lowered.add("local" + localSlot);
        localSlot += ("long".equals(type) || "double".equals(type)) ? 2 : 1;
      }
    }
    return String.join(", ", lowered);
  }

  private static String exportedName(String name, String descriptor) {
    String suffix = Integer.toUnsignedString(
        (descriptor == null ? "" : descriptor).hashCode(), 36);
    return safeIdentifier(name) + "__" + suffix;
  }

  private static String safeIdentifier(String value) {
    String safe = value == null ? "translatedMethod" : value.replaceAll("[^A-Za-z0-9_$]", "_");
    if (safe.isBlank()) safe = "translatedMethod";
    if (!Character.isJavaIdentifierStart(safe.charAt(0))) safe = "_" + safe;
    return safe;
  }

  private static String quote(String value) {
    return "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"")
        .replace("\n", "\\n").replace("\r", "\\r") + "\"";
  }

  private static String escapeChar(char value) {
    return switch (value) {
      case '\n' -> "\\n";
      case '\r' -> "\\r";
      case '\t' -> "\\t";
      case '"' -> "\\\"";
      default -> String.valueOf(value);
    };
  }

  private enum LexicalState { CODE, STRING, CHARACTER, LINE_COMMENT, BLOCK_COMMENT }
}